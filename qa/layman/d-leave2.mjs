import { asRole, go, mainText, sleep, close, snap } from "./d-h.mjs";
const p = await asRole("hr");
const dlg = () => p.getByRole("dialog").last();
const setD = async (loc, v) => { await loc.click({ clickCount: 3 }); await p.keyboard.press("Control+A"); await p.keyboard.type(v); await p.keyboard.press("Tab"); await sleep(300); };
const vals = async (tag) => console.log(tag, "| from box:", await dlg().locator("input[id$=-from]").inputValue(), "hidden:", await dlg().locator("input[name=from]").inputValue().catch(() => "?"), "| to box:", await dlg().locator("input[id$=-to]").inputValue(), "| reason:", await dlg().locator("[name=reason]").inputValue(), "| type:", await dlg().locator("[name=leaveTypeId]").inputValue(), "| staff:", await dlg().locator("[name=staffId]").inputValue());
await go(p, "/staff-hr-management/leave"); await sleep(1500);
await p.getByRole("button", { name: /Apply for leave/ }).first().click(); await sleep(1500);
const st = dlg().locator("[name=staffId]");
const l = (await st.locator("option").allInnerTexts()).find((x) => x.includes("LD-")); await st.selectOption({ label: l });
await dlg().locator("[name=leaveTypeId]").selectOption({ index: 2 });
await setD(dlg().locator("input[id$=-from]"), "20-11-2026");
await setD(dlg().locator("input[id$=-to]"), "18-11-2026");
await dlg().locator("[name=reason]").fill("LD- repro");
await vals("BEFORE submit");
await dlg().getByRole("button", { name: /Apply|Send|Submit/ }).last().click(); await sleep(2500);
console.log("msg:", (await dlg().innerText()).split("\n").filter((x) => /before|after|date/i.test(x)).slice(0, 3).join(" / "));
await vals("AFTER refused");
await snap(p, "leave2-after-refused", false);
await p.keyboard.press("Escape");
await close();
