// Night B: cancel a payment with a reason (empty first), then check ledger + Day Book.  node nb-cancel.mjs <studentId> <paymentId> <reasonLabel> [bounceCharge]
import { asRole, go, mainText, sleep, snap, log, flat } from "./nb-h.mjs";
const L = log("cancel");
const [sid, pid, why, charge] = process.argv.slice(2);
const p = await asRole("accountant");
await go(p, `/fee-management/payments/${pid}`); await sleep(1500);
await p.getByRole("link", { name: /Cancel with a reason/ }).click(); await sleep(2500);
const dlg = p.getByRole("dialog").last();
L("CANCEL SHEET", flat(await dlg.innerText()).slice(0, 1200));
await snap(p, "cancel-sheet", false);
const go2 = dlg.getByRole("button", { name: /Cancel (this )?payment|Cancel receipt|Confirm/ }).last();
L("CANCEL BTN", await go2.innerText().catch(() => "?"));
await go2.click().catch((e) => L("click err", e.message.slice(0, 100))); await sleep(2500);
L("EMPTY ->", flat(await dlg.innerText().catch(() => "closed")).slice(0, 800));
const sel = dlg.locator("select[name=reason]");
const opts = await sel.locator("option").allInnerTexts(); L("REASONS", opts.join(" ; "));
await sel.selectOption({ label: why }); await sleep(500);
if (charge) await dlg.locator("input[name=bounceCharge]").fill(charge);
await dlg.locator("textarea[name=note]").fill("NB- night test, cheque returned by bank");
const t0 = Date.now();
await go2.dblclick(); 
for (let i = 0; i < 40 && await dlg.isVisible().catch(() => false); i++) await sleep(1000);
L("AFTER", Date.now() - t0, "ms open:", await dlg.isVisible().catch(() => false), flat(await mainText(p, 1500)).slice(0, 600));
await snap(p, "cancel-after", false);
await go(p, `/fee-management/payments/${pid}`); await sleep(1500);
L("PAYMENT NOW", flat(await p.getByRole("dialog").last().innerText().catch(() => "")).slice(0, 800));
await go(p, `/fee-management/ledger/${sid}`); await sleep(1000);
L("LEDGER TOP", flat((await mainText(p, 1200))).slice(0, 700));
await go(p, "/finance-management/day-book"); await sleep(1000);
const b = await mainText(p, 8000);
L("DAYBOOK", flat(b.match(/Total income[\s\S]{0,300}/)?.[0]), "||", flat(b.match(/Refunds and reversals[\s\S]{0,400}/)?.[0]));
process.exit(0);
