await save().dblclick(); await sleep(500); await idle(); await sleep(3000);
log("after save url", p.url());
log("after save text", (await mainText(p, 1500)).replace(/\n/g, " | "));
await snap(p, "sn2-saved");
await go(p, `/student-management?q=${encodeURIComponent("Student " + S)}`); await sleep(1500);
const lt = await mainText(p, 6000);
log("rows with name", (lt.match(new RegExp(`Student ${S}`, "g")) ?? []).length);
log("list", lt.slice(lt.indexOf("Reset all"), lt.indexOf("Reset all") + 600).replace(/\n/g, " | "));
console.log("PROBLEMS", p.problems);
