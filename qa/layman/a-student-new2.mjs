const dob = () => p.locator("main input[id$=-dateOfBirth]");
const save = () => p.getByRole("button", { name: /Add student|Adding/ }).last();
const idle = async () => { for (let i = 0; i < 40; i++) { if (!/Adding/.test(await save().innerText().catch(() => ""))) return; await sleep(500); } };
await go(p, "/student-management/new"); await sleep(800);
log("maxlength on name", await f("fullName").getAttribute("maxlength"));
await f("fullName").fill("LA-" + "రామకృష్ణ ".repeat(30));
await f("sectionId").selectOption({ index: 4 });
await dob().pressSequentially("10-06-2019", { delay: 10 }); await p.keyboard.press("Tab");
await p.locator("main").getByText("Female", { exact: true }).click();
await f("guardianPhone").fill("97040" + S);
await f("guardianName").fill("LA-Parent " + S);
await f("rollNo").fill("");
const t0 = Date.now();
await save().click(); await sleep(500); await idle();
log("server answer took ms", Date.now() - t0);
log("top message", (await mainText(p, 600)).match(/Full name[^\n]*/)?.[0]);
log("after refuse: dob", await dob().inputValue());
log("after refuse: phone", await f("guardianPhone").inputValue());
log("after refuse: parent name", await f("guardianName").inputValue());
log("after refuse: section", await f("sectionId").inputValue());
log("after refuse: female checked", await p.locator("main input[name=gender][value]").evaluateAll((els) => els.filter((e) => e.checked).map((e) => e.value)));
await snap(p, "sn2-after-refuse");
