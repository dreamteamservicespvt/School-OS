await d.getByRole("button", { name: /Send to Admissions/ }).dblclick(); await sleep(4000);
log(`ENQ saved: dialog visible=${await d.isVisible().catch(() => false)} toasts=${(await p.locator("[data-sonner-toast]").allInnerTexts().catch(() => [])).join(" / ")} errs=${await errs()}`);
