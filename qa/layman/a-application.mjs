// Layman A: Convert enquiry to application (empty save, future DOB, very long address, consent code, double save).
import { asRole, go, mainText, sleep, close, snap } from "../full/selftest-A-h.mjs";
const { logSize, waitLog } = await import("../full/h.mjs");
const ENQ = process.argv[2]; const PH4 = process.argv[3];
const p = await asRole("admin");
const log = (k, v) => console.log(`== ${k}: ${typeof v === "string" ? v : JSON.stringify(v)}`);
const f = (n) => p.locator(`main [name=${n}]`);
const errs = async () => [...new Set((await p.locator('main [id$="-error"], main [role="alert"]').allInnerTexts()).map((x) => x.trim()).filter(Boolean))];
const save = () => p.getByRole("button", { name: /Save application|Saving/ });
await go(p, `/admission-management/applications/new?enquiry=${ENQ}`); await sleep(1000);
log("prefill", { year: await p.locator("main select[name=yearId] option:checked").innerText(), cls: await p.locator("main select[name=classId] option:checked").innerText(), first: await f("firstName").inputValue(), last: await f("lastName").inputValue(), phone: await f("phone").inputValue() });
await save().click(); await sleep(1500);
log("empty errors", await errs()); await snap(p, "app-empty", false);
const dob = p.locator("main input[id$=-dateOfBirth]");
await dob.pressSequentially("29-02-2023", { delay: 10 }); await p.keyboard.press("Tab"); await sleep(300);
log("29 Feb 2023 errors", await errs());
await dob.fill(""); await dob.pressSequentially("15-08-2030", { delay: 10 }); await p.keyboard.press("Tab");
await f("address").fill("LA ".repeat(800));
await p.locator("main").getByText("Boy", { exact: true }).click();
await f("fatherName").fill("LA-राजेश शर्मा");
await save().click(); await sleep(2500);
log("future dob + long address errors", await errs()); await snap(p, "app-future", false);
await dob.fill(""); await dob.pressSequentially("05-05-2022", { delay: 10 }); await p.keyboard.press("Tab");
await f("address").fill("LA-12-3, ఆదర్శ నగర్, హైదరాబాద్ 500001");
await save().click(); await sleep(2500);
log("without consent errors", await errs()); log("url", p.url());
await snap(p, "app-noconsent", false);
if (p.url().includes("/new")) {
  const from = logSize();
  await p.getByRole("button", { name: "Send one-time code" }).click();
  const m = await waitLog(from, new RegExp("one-time code[^\\n]*" + PH4 + "[^\\n]*: ([0-9]{4,6})"), 60000);
  log("code arrived", !!m);
  await sleep(800);
  await p.locator("main input[autocomplete=one-time-code], main input[inputmode=numeric]").last().pressSequentially(m?.[1] ?? "000000", { delay: 30 });
  const conf = p.getByRole("button", { name: /confirm|verify|check/i }).first();
  if (await conf.isVisible().catch(() => false)) await conf.click();
  await sleep(1500);
  log("consent area", ((await mainText(p, 8000)).match(/CONSENT[\s\S]{0,300}/)?.[0] ?? "").replace(/\n/g, " | "));
  await save().dblclick();
  await p.waitForURL((u) => !u.pathname.endsWith("/new"), { timeout: 30000 }).catch(() => {});
  await sleep(2500);
}
log("saved url", p.url());
log("saved text", (await mainText(p, 2500)).replace(/\n/g, " | "));
await snap(p, "app-saved");
await go(p, `/admission-management/applications?q=${PH4}`); await sleep(1200);
const t = await mainText(p, 5000);
log("applications list", t.slice(Math.max(0, t.indexOf("Showing") - 600), t.indexOf("Showing") + 30).replace(/\n/g, " | "));
console.log("PROBLEMS", p.problems);
await close();
