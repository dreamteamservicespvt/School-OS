import { asRole, go, mainText, sleep, close, snap } from "./d-h.mjs";
const p = await asRole("warden");
const errs = []; p.on("pageerror", (e) => errs.push(e.message.slice(0, 200)));
const dlg = () => p.getByRole("dialog").last();
const scope = async () => (await dlg().isVisible().catch(() => false)) ? dlg() : p.locator("main");
const setD = async (loc, v) => { await loc.click({ clickCount: 3 }); await p.keyboard.press("Control+A"); await p.keyboard.type(v); await p.keyboard.press("Tab"); await sleep(300); };
await go(p, "/hostel-management/outings?new=1"); await sleep(2500);
const s = await scope();
console.log("OUTING FORM:", (await s.innerText()).replace(/\n+/g, " | ").slice(0, 900));
const sub = s.locator("button[type=submit]").last();
console.log("submit:", await sub.innerText().catch(() => "?"));
await sub.click(); await sleep(2500);
console.log("EMPTY:", (await s.locator("[id$=-error], [role=alert]").allInnerTexts().catch(() => [])).join(" / "));
const stu = s.locator("[name=studentId]");
console.log("student field:", await stu.evaluate((e) => e.tagName + "/" + e.type).catch(() => "none"));
if ((await stu.evaluate((e) => e.tagName).catch(() => "")) === "SELECT") await stu.selectOption({ index: 1 });
await s.locator("[name=outingType]").selectOption({ index: 1 }).catch(() => {});
for (const [n, v] of [["fromDate", "20-11-2026"], ["toDate", "18-11-2026"]]) await setD(s.locator(`input[id$=-${n}]`).first(), v).catch((e) => console.log(n, e.message.slice(0, 60)));
await s.locator("[name=place]").fill("LD-ఇంటికి Home").catch(() => {});
await s.locator("[name=reason]").fill("LD- test").catch(() => {});
await s.locator("[name=withName]").fill("LD Parent").catch(() => {});
await s.locator("[name=withPhone]").fill("12345").catch(() => {});
await sub.click(); await sleep(3000);
console.log("TO<FROM, phone 12345:", (await s.locator("[id$=-error], [role=alert]").allInnerTexts().catch(() => [])).join(" / "));
await snap(p, "hostel-outing-bad");
console.log("values after:", await s.locator("input[name=fromDate]").inputValue().catch(() => "?"), await s.locator("input[name=toDate]").inputValue().catch(() => "?"));
// allocation sheet
await go(p, "/hostel-management/allocation?allocate=1"); await sleep(2500);
const a = await scope();
console.log("\nALLOCATE FORM:", (await a.innerText()).replace(/\n+/g, " | ").slice(0, 700));
await snap(p, "hostel-allocate");
const asub = a.locator("button[type=submit]").last();
await asub.click(); await sleep(2500);
console.log("ALLOC EMPTY:", (await a.locator("[id$=-error], [role=alert]").allInnerTexts().catch(() => [])).join(" / "));
console.log("ERRS", errs);
await close();
