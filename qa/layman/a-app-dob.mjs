import { asRole, go, mainText, sleep, close, snap } from "../full/selftest-A-h.mjs";
const { logSize, waitLog } = await import("../full/h.mjs");
const ENQ = process.argv[2]; const PH4 = process.argv[3];
const p = await asRole("admin");
const log = (k, v) => console.log(`== ${k}: ${typeof v === "string" ? v : JSON.stringify(v)}`);
const f = (n) => p.locator(`main [name=${n}]`);
const dob = p.locator("main input[id$=-dateOfBirth]");
const hiddenDob = p.locator("main input[type=hidden][name=dateOfBirth]");
const save = () => p.getByRole("button", { name: /Save application|Saving/ });
await go(p, `/admission-management/applications/new?enquiry=${ENQ}`); await sleep(1000);
await dob.pressSequentially("15-08-2030", { delay: 10 }); await p.keyboard.press("Tab");
await f("address").fill("LA-12-3, ఆదర్శ నగర్, హైదరాబాద్ 500001");
await p.locator("main").getByText("Boy", { exact: true }).click();
await f("fatherName").fill("LA-राजेश शर्मा");
const from = logSize();
await p.getByRole("button", { name: /Send one-time code|Send again/ }).click();
const m = await waitLog(from, new RegExp("one-time code[^\n]*" + PH4 + "[^\n]*: ([0-9]{4,6})"), 60000);
await sleep(800);
await p.locator("main input[autocomplete=one-time-code], main input[inputmode=numeric]").last().pressSequentially(m?.[1] ?? "000000", { delay: 30 });
const conf = p.getByRole("button", { name: /^Confirm$/ }).first();
if (await conf.isVisible().catch(() => false)) await conf.click();
await sleep(1500);
log("hidden before 1st save", await hiddenDob.inputValue().catch(() => "?"));
await save().click(); await sleep(4000);
log("after 1st save: box", await dob.inputValue()); log("after 1st save: hidden", await hiddenDob.inputValue().catch(() => "?"));
log("msg", ((await mainText(p, 1500)).match(/[^\n]*(future|birth)[^\n]*/gi) ?? []).join(" / "));
// layman correction: click into box, select all, type the right date
await dob.click(); await p.keyboard.press("Control+A"); await p.keyboard.press("Backspace");
await dob.pressSequentially("05-05-2022", { delay: 30 }); await p.keyboard.press("Tab"); await sleep(300);
log("after correcting: box", await dob.inputValue()); log("after correcting: hidden", await hiddenDob.inputValue().catch(() => "?"));
log("consent still confirmed", /Data consent given/.test(await mainText(p, 8000)));
await save().click();
await p.waitForURL((u) => !u.pathname.endsWith("/new"), { timeout: 20000 }).catch(() => {});
await sleep(2500);
log("after 2nd save url", p.url());
const t = await mainText(p, 3000);
log("after 2nd save", t.slice(0, 1600).replace(/\n/g, " | "));
await snap(p, "appdob-after");
console.log("PROBLEMS", p.problems);
