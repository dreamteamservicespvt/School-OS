import { asRole, go, sleep, close, snap, one, timed, watch } from "./nc-h.mjs";
const p = watch(await asRole("teacher"));
await go(p, "/homework-learning?do=give"); await sleep(1200);
const sheet = () => p.locator("form:has(#f-title)").first();
const send = () => p.locator("button[type=submit]", { hasText: /Send to/ }).first();
const btn = (t) => sheet().locator("button", { hasText: t }).first();
const val = async (s) => p.locator(s).inputValue().catch(() => "?");
await btn(/^\s*5 B/).click();
await p.locator("#f-title").fill("NC- check boxes");
await btn("Tomorrow").click(); await sleep(400);
console.log("after Tomorrow:", one(await sheet().innerText(), 2000).match(/Pick a date \| ([^|]+)/)?.[1], "pressed:", await btn("Tomorrow").getAttribute("aria-pressed"), await btn("Tomorrow").getAttribute("aria-checked"));
await btn("More details").click().catch(() => {}); await sleep(500);
await p.locator("#gh-max").click(); await p.locator("#gh-max").press("Control+a"); await p.locator("#gh-max").pressSequentially("abc", { delay: 20 });
console.log("max after typing abc:", await val("#gh-max"));
await p.locator("#gh-max").press("Control+a"); await p.locator("#gh-max").pressSequentially("150", { delay: 20 });
console.log("max after typing 150:", await val("#gh-max"));
const b = p.locator("#gh-start"); await b.click(); await b.press("Control+a"); await b.pressSequentially("20112026", { delay: 30 }); await b.press("Tab");
console.log("start after typing 20112026:", await val("#gh-start"));
await snap(p, "hw4-before-send");
await send().click(); await sleep(2000);
console.log("ERR TEXT:", one(await sheet().innerText(), 2500).split("|").filter(s => /must|cannot|after|before|no day|check/i.test(s)).join(" | "));
console.log("after send: max", await val("#gh-max"), "start", await val("#gh-start"), "title", await val("#f-title"));
await snap(p, "hw4-after-send");
console.log("PROBLEMS", p.problems);
await close();
