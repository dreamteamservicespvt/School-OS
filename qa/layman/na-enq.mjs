const errs = async () => (await d.innerText().catch(() => "closed")).split("\n").filter((l) => /need|choose|enter|type|letters|digit|valid|must|can/i.test(l)).join(" | ");
await d.locator('input[name="childName"]').pressSequentially("😀😀");
await d.locator('input[name="parentName"]').pressSequentially("1");
await d.locator("#en-phone").pressSequentially("98480");
await d.getByRole("button", { name: /Send to Admissions/ }).click(); await sleep(2000);
log("ENQ emoji/1/short phone: " + await errs());
