import { asRole, go, mainText, sleep, close, snap } from "./d-h.mjs";
const p = await asRole("admin");
const dlg = () => p.getByRole("dialog").last();
const errsIn = async () => (await dlg().innerText().catch(() => "")).split("\n").filter((x) => /before|after|end|later|past|must|need|long|character/i.test(x)).join(" / ");
const setD = async (loc, v) => { await loc.click({ clickCount: 3 }); await p.keyboard.press("Control+A"); await p.keyboard.type(v); await p.keyboard.press("Tab"); await sleep(300); };
const S = new Date().toISOString().slice(11, 16).replace(":", "");
await go(p, "/events-calendar/events?do=create"); await sleep(2000);
const save = () => dlg().getByRole("button", { name: "Create event" });
await dlg().locator("[name=name]").fill(`LD-Endtest ${S}`);
await dlg().locator("[name=type]").selectOption({ index: 2 });
await setD(dlg().locator("input[id$=-date]").first(), "27-11-2026");
const st = dlg().locator("input[id$=-startTime]").first(), en = dlg().locator("input[id$=-endTime]").first();
await st.click({ clickCount: 3 }); await p.keyboard.press("Control+A"); await p.keyboard.type("3:00 PM"); await p.keyboard.press("Tab");
await en.click({ clickCount: 3 }); await p.keyboard.press("Control+A"); await p.keyboard.type("10:00 AM"); await p.keyboard.press("Tab");
await sleep(300);
console.log("values:", await dlg().locator("input[name=date]").inputValue(), await dlg().locator("input[name=startTime]").inputValue(), await dlg().locator("input[name=endTime]").inputValue());
await save().click();
for (let i = 0; i < 30; i++) { await sleep(1000); if (!(await dlg().isVisible().catch(() => false))) break; if (await save().isEnabled().catch(() => false)) break; } console.log("waited");
console.log("END<START result:", await errsIn(), "| open:", await dlg().isVisible().catch(() => false));
await snap(p, "ev2-end-before-start", false);
await go(p, "/events-calendar/events"); await sleep(1500);
const t = await mainText(p, 40000);
console.log("created?", t.split("\n").map((x, i, a) => x.includes(`Endtest ${S}`) ? a.slice(i, i + 4).join(" ") : null).filter(Boolean).join(" || "));
await close();
