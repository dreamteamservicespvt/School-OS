// Builds src/lib/page-index.ts: every page inside a module, with its screen
// title, so the top search box finds it (team test 13-11: a Receptionist
// searched "Postal" and got nothing, because search only knew module names).
// Run: node scripts/gen-page-index.mjs   (tests/page-index.test.ts fails when the file is out of date)
import { readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { join, relative, sep } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = fileURLToPath(new URL("..", import.meta.url));
const APP = join(ROOT, "src", "app", "(school)");
export const OUT = join(ROOT, "src", "lib", "page-index.ts");

function walk(dir, out = []) {
  for (const name of readdirSync(dir)) {
    const p = join(dir, name);
    if (statSync(p).isDirectory()) {
      if (name.startsWith("[") || name.startsWith("_") || name.startsWith("(")) continue;
      walk(p, out);
    } else if (name === "page.tsx") out.push(p);
  }
  return out;
}

export function buildIndex() {
  const rows = [];
  for (const file of walk(APP)) {
    const parts = relative(APP, file).split(sep).slice(0, -1);
    if (parts.length < 2) continue; // a module's own page is already in the menu
    const m = readFileSync(file, "utf8").match(/pageTitle\("([^"]+)"\)/);
    if (!m) continue;
    rows.push({ href: `/${parts.join("/")}`, module: parts[0], title: m[1] });
  }
  rows.sort((a, b) => a.href.localeCompare(b.href));
  return `// Generated by scripts/gen-page-index.mjs. Do not edit by hand.\n// Every page inside a module and its title, for the top search box.\nexport const PAGE_INDEX: { href: string; module: string; title: string }[] = [\n${rows.map((r) => `  { href: ${JSON.stringify(r.href)}, module: ${JSON.stringify(r.module)}, title: ${JSON.stringify(r.title)} },`).join("\n")}\n];\n`;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  writeFileSync(OUT, buildIndex());
  console.log(`Wrote ${relative(ROOT, OUT)}`);
}
