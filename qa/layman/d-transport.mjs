import { asRole, go, mainText, sleep, close, snap } from "./d-h.mjs";
const p = await asRole("transport");
const errs = []; p.on("pageerror", (e) => errs.push(e.message.slice(0, 200)));
const dlg = () => p.getByRole("dialog").last();
const E = async () => (await dlg().locator("[id$=-error], [role=alert]").allInnerTexts().catch(() => [])).filter(Boolean).join(" / ");
const wait = async () => { for (let i = 0; i < 25; i++) { await sleep(800); if (!(await dlg().isVisible().catch(() => false))) return; if (await dlg().locator("button[type=submit]").last().isEnabled().catch(() => true)) return; } };
await go(p, "/transport-management/students?do=assign"); await sleep(2500);
console.log("ASSIGN FORM:", (await dlg().innerText().catch(() => "none")).replace(/\n+/g, " | ").slice(0, 800));
await snap(p, "tr-assign", false);
const sub = () => dlg().locator("button[type=submit]").last();
console.log("submit:", await sub().innerText().catch(() => "?"));
await sub().click(); await wait();
console.log("EMPTY:", await E());
await p.keyboard.press("Escape");
await go(p, "/transport-management/routes?do=route"); await sleep(2500);
console.log("\nROUTE FORM:", (await dlg().innerText().catch(() => "none")).replace(/\n+/g, " | ").slice(0, 800));
await sub().click(); await wait();
console.log("ROUTE EMPTY:", await E());
const names = await dlg().locator("input[name], select[name], textarea[name]").evaluateAll((els) => els.map((e) => `${e.name}:${e.type}:${e.id}`));
console.log("fields:", names.join(", "));
await snap(p, "tr-route", false);
await go(p, "/transport-management/vehicles"); await sleep(2000);
const t = await mainText(p, 4000);
console.log("\nVEHICLES:", t.replace(/\n+/g, " | ").slice(0, 600));
const ex = await p.request.get("http://localhost:3000/transport-management/export?what=routes&format=xlsx");
console.log("export no params ->", ex.status(), (await ex.text()).slice(0, 120));
console.log("ERRS", errs);
await close();
