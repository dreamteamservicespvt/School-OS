log("count NA-अनन्या in desk list: " + (t.match(/NA-अनन्या रेड्डी 01/g) ?? []).length + " :: " + (t.match(/NA-अनन्या[^\n]*\n[^\n]*/) ?? [""])[0].replace(/\n/g, " | "));
