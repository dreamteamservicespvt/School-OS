import { asRole, go, sleep, close, snap, one, timed, watch } from "./nc-h.mjs";
const p = watch(await asRole("teacher"));
await go(p, "/homework-learning?do=give"); await sleep(1200);
const sheet = () => p.locator("form:has(#f-title)").first();
const send = () => p.locator("button[type=submit]", { hasText: /Send to/ }).first();
const btn = (t) => sheet().locator("button", { hasText: t }).first();
const msg = async (tag) => { await sleep(1500); console.log(tag, "::", one(await sheet().innerText().catch(() => "(closed) " + p.url()), 1500)); };
const typeDate = async (sel, digits) => { const b = p.locator(sel); await b.click(); await b.press("Control+a"); await b.pressSequentially(digits, { delay: 20 }); await b.press("Tab"); };
await btn(/^\s*6 A/).click();
await p.locator("#f-title").pressSequentially("NC- गृहकार्य అభ్యాసం 5.1 🙂", { delay: 5 });
await btn("Tomorrow").click();
await btn("More details").click().catch(() => {}); await sleep(500);
await p.locator("#gh-max").fill("abc");
await typeDate("#gh-start", "20112026");
await send().click(); await msg("BADMAX+START>DUE");
await snap(p, "hw-bad");
console.log("title kept:", await p.locator("#f-title").inputValue().catch(() => "?"), " start:", await p.locator("#gh-start").inputValue().catch(() => "?"), " max:", await p.locator("#gh-max").inputValue().catch(() => "?"));
await p.locator("#gh-max").fill("25");
await typeDate("#gh-start", "31022026");
await send().click(); await msg("31-02");
console.log("start:", await p.locator("#gh-start").inputValue().catch(() => "?"));
await typeDate("#gh-start", "13112026");
const t0 = Date.now();
await send().dblclick();
await p.waitForFunction(() => !document.querySelector("#f-title"), null, { timeout: 60000 }).catch(() => {});
console.log("SAVE took", Date.now() - t0, "ms; url", p.url());
await sleep(1500);
console.log("AFTER", one(await p.locator("main").innerText(), 1500));
await snap(p, "hw-saved");
console.log("PROBLEMS", p.problems);
await close();
